/// Selects SQL lexing rules and keywords, and also how completion names database objects.
///
/// Choosing a family also chooses whether database names are offered as the table namespace, whether table candidates are schema-qualified, how qualifiers match case, and whether candidates are backtick-quoted.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum LexicalFamily {
    PostgreSql,
    MySql,
}

impl LexicalFamily {
    pub fn keywords(self) -> &'static [&'static str] {
        match self {
            Self::PostgreSql => POSTGRESQL_KEYWORDS,
            Self::MySql => MYSQL_KEYWORDS,
        }
    }

    pub fn completion_keywords(self) -> impl Iterator<Item = &'static str> {
        let hidden = match self {
            Self::PostgreSql => POSTGRESQL_KEYWORDS_HIDDEN_FROM_COMPLETION,
            Self::MySql => MYSQL_KEYWORDS_HIDDEN_FROM_COMPLETION,
        };
        self.keywords()
            .iter()
            .copied()
            .filter(move |keyword| !hidden.contains(keyword))
    }
}

